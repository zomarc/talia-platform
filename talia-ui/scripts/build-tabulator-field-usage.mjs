/**
 * Scans focus-panel Tabulator column `field:` declarations and writes a static
 * application-wide usage catalog for Column Terminology.
 *
 * Usage: node ./scripts/build-tabulator-field-usage.mjs
 */
import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import { dirname, extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const FOCUS_PANELS_DIR = join(ROOT, 'src', 'components', 'focus-panels');
const REGISTRY_PATH = join(FOCUS_PANELS_DIR, 'registry.js');
const DICTIONARY_PATH = join(ROOT, 'src', 'lib', 'tabulatorColumnLabelDictionary.js');
const OUTPUT_PATH = join(ROOT, 'src', 'lib', 'tabulatorFieldUsageCatalog.js');
const FILE_EXTENSIONS = new Set(['.js', '.jsx', '.ts', '.tsx']);
const FIELD_PATTERN = /field:\s*['"]([A-Za-z0-9_]+)['"]/g;
const SKIP_PANEL_IDS = new Set([
  'column-terminology',
  'test-workbench',
  'breakout-game',
  'space-invaders',
  'pac-man',
  'asteroids',
  'pong',
  'moon-lander',
  'btop-terminal',
]);

const walk = async (dir, out = []) => {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(fullPath, out);
      continue;
    }
    if (!FILE_EXTENSIONS.has(extname(entry.name))) continue;
    const fileStat = await stat(fullPath);
    if (!fileStat.isFile()) continue;
    out.push(fullPath);
  }
  return out;
};

const loadAliases = async () => {
  const text = await readFile(DICTIONARY_PATH, 'utf8');
  const aliases = {};
  const block = text.match(/FIELD_ALIASES\s*=\s*\{([\s\S]*?)\};/);
  if (!block) return aliases;
  const pairPattern = /([A-Za-z0-9_]+)\s*:\s*['"]([A-Za-z0-9_]+)['"]/g;
  let match;
  while ((match = pairPattern.exec(block[1]))) {
    aliases[match[1]] = match[2];
  }
  return aliases;
};

const loadRegistryPanels = async () => {
  const text = await readFile(REGISTRY_PATH, 'utf8');
  const panels = [];
  const entryPattern = /(\w+)\s*:\s*\{([\s\S]*?)\n  \},/g;
  let match;
  while ((match = entryPattern.exec(text))) {
    const body = match[2];
    const panelId = body.match(/panelId:\s*['"]([^'"]+)['"]/)?.[1];
    const filePath = body.match(/filePath:\s*['"]([^'"]+)['"]/)?.[1];
    if (!panelId || !filePath) continue;
    panels.push({
      registryKey: match[1],
      panelId,
      folder: dirname(join(ROOT, filePath)),
    });
  }
  return panels;
};

const extractFields = (content, aliases) => {
  const fields = new Set();
  let match;
  FIELD_PATTERN.lastIndex = 0;
  while ((match = FIELD_PATTERN.exec(content))) {
    const raw = match[1];
    const canonical = aliases[raw] || raw;
    fields.add(canonical);
  }
  return fields;
};

const main = async () => {
  const aliases = await loadAliases();
  const panels = await loadRegistryPanels();
  const byField = new Map();

  for (const panel of panels) {
    if (SKIP_PANEL_IDS.has(panel.panelId)) continue;
    let files = [];
    try {
      files = await walk(panel.folder);
    } catch {
      continue;
    }
    const panelFields = new Set();
    for (const file of files) {
      const content = await readFile(file, 'utf8');
      if (!content.includes('field:')) continue;
      extractFields(content, aliases).forEach((field) => panelFields.add(field));
    }
    panelFields.forEach((field) => {
      const list = byField.get(field) || new Set();
      list.add(panel.panelId);
      byField.set(field, list);
    });
  }

  const catalog = Object.fromEntries(
    Array.from(byField.entries())
      .sort((a, b) => a[0].localeCompare(b[0]))
      .map(([field, components]) => [field, Array.from(components).sort((a, b) => a.localeCompare(b))])
  );

  const generatedAt = new Date().toISOString();
  const body = `/**
 * AUTO-GENERATED by scripts/build-tabulator-field-usage.mjs
 * Do not edit by hand. Regenerate with: npm run build:field-usage
 *
 * Generated: ${generatedAt}
 * Maps canonical Tabulator field -> registry panelId list (application-wide).
 */

const TABULATOR_FIELD_USAGE_CATALOG = ${JSON.stringify(catalog, null, 2)};

export const getAppTabulatorFieldComponents = (field = '') => {
  const key = String(field || '').trim();
  if (!key) return [];
  const components = TABULATOR_FIELD_USAGE_CATALOG[key];
  return Array.isArray(components) ? components : [];
};

export const getAppTabulatorFieldUsageRows = () => (
  Object.entries(TABULATOR_FIELD_USAGE_CATALOG)
    .map(([field, components]) => ({
      field,
      components: Array.isArray(components) ? components : [],
      componentCount: Array.isArray(components) ? components.length : 0,
    }))
    .sort((a, b) => a.field.localeCompare(b.field))
);

export default TABULATOR_FIELD_USAGE_CATALOG;
`;

  await writeFile(OUTPUT_PATH, body, 'utf8');
  const fieldCount = Object.keys(catalog).length;
  const componentLinks = Object.values(catalog).reduce((sum, list) => sum + list.length, 0);
  console.log(
    `Wrote ${relative(ROOT, OUTPUT_PATH)} (${fieldCount} fields, ${componentLinks} field→panel links, ${panels.length} registry panels scanned).`
  );
};

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
