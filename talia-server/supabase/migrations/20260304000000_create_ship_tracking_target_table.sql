-- Configurable ship tracking catalog for Ship Tracker Map.
-- Allows separating Celestyal ships from other tracked ships and
-- adding external examples (e.g., Costa Toscana).

create table if not exists public.ship_tracking_target (
  id bigint generated by default as identity primary key,
  ship_code text not null unique,
  ship_name text not null,
  operator_name text not null default 'Other',
  fleet_group text not null default 'other' check (fleet_group in ('celestyal', 'other')),
  region_scope text[] not null default array[]::text[],
  mmsi text null,
  imo_number text null,
  home_port_label text null,
  home_latitude double precision null,
  home_longitude double precision null,
  enabled boolean not null default true,
  display_order integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_ship_tracking_target_enabled
  on public.ship_tracking_target(enabled);

create index if not exists idx_ship_tracking_target_group_order
  on public.ship_tracking_target(fleet_group, display_order, ship_code);

create or replace function public.set_ship_tracking_target_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_ship_tracking_target_updated_at on public.ship_tracking_target;
create trigger trg_ship_tracking_target_updated_at
before update on public.ship_tracking_target
for each row execute procedure public.set_ship_tracking_target_updated_at();

